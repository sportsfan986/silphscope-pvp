#!/usr/bin/env node
/**
 * SilphScope PvP — Cross-Platform PvPoke Shadow Eligibility Baseline Sync
 *
 * Usage:
 *   node scripts/sync-pvpoke-shadows.mjs                  # Fetch live PvPoke gamemaster.json + sync KT/TS/Worker
 *   node scripts/sync-pvpoke-shadows.mjs --local-file <p> # Parse a local gamemaster.json copy instead of fetching
 *   node scripts/sync-pvpoke-shadows.mjs --no-worker      # Skip rebuilding cloudflare/telemetry-worker/overlay-asset.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT = path.resolve(__dirname, "..");

const GAMEMASTER_URL =
  "https://raw.githubusercontent.com/pvpoke/pvpoke/master/src/data/gamemaster.json";
const KT_DB_PATH = path.join(ROOT, "app", "src", "main", "java", "com", "gbl", "overlay", "PokemonDatabase.kt");
const TS_BASELINE_PATH = path.join(ROOT, "src", "data", "shadowBaseline.ts");
const WORKER_GEN_SCRIPT = path.join(ROOT, "scripts", "generate-worker-overlay.mjs");

const argv = process.argv.slice(2);
const noWorker = argv.includes("--no-worker");
let localFile = "";
const lfIdx = argv.indexOf("--local-file");
if (lfIdx !== -1 && argv[lfIdx + 1]) {
  localFile = path.resolve(argv[lfIdx + 1]);
}

async function loadGamemaster() {
  if (localFile) {
    return JSON.parse(fs.readFileSync(localFile, "utf8"));
  }
  const res = await fetch(GAMEMASTER_URL, {
    headers: { "User-Agent": "SilphScope-PvP-Shadow-Sync/1.0" },
  });
  if (!res.ok) {
    throw new Error(`Failed to fetch ${GAMEMASTER_URL}: HTTP ${res.status} ${res.statusText}`);
  }
  return res.json();
}

function extractShadowKeys(gm) {
  if (!gm || !Array.isArray(gm.pokemon)) {
    throw new Error("Invalid gamemaster.json: missing pokemon array.");
  }
  const keys = new Set();
  for (const p of gm.pokemon) {
    if (!p || typeof p.speciesId !== "string" || typeof p.speciesName !== "string") continue;
    const rawId = p.speciesId.trim();
    const rawName = p.speciesName.trim();
    const idLowerRaw = rawId.toLowerCase();
    const nameLowerRaw = rawName.toLowerCase();

    if (
      idLowerRaw === "mewtwo_armored" ||
      nameLowerRaw.includes("armored") ||
      idLowerRaw.includes("_mega") ||
      idLowerRaw.includes("_primal") ||
      nameLowerRaw.startsWith("mega ") ||
      nameLowerRaw.startsWith("primal ")
    ) {
      continue;
    }

    const hasShadowTag =
      idLowerRaw.endsWith("_shadow") ||
      (Array.isArray(p.tags) &&
        p.tags.some((t) => typeof t === "string" && t.toLowerCase() === "shadoweligible"));
    if (!hasShadowTag) continue;

    const cleanBaseId = idLowerRaw.replace(/_shadow$/, "").trim();
    if (cleanBaseId) {
      keys.add(cleanBaseId);
      if (cleanBaseId.includes("-")) {
        keys.add(cleanBaseId.replace(/-/g, "_"));
      }
    }

    const cleanDisplay = rawName
      .replace(/\s*\(Shadow\)\s*$/i, "")
      .replace(/^Shadow\s+/i, "")
      .trim()
      .toLowerCase();
    if (cleanDisplay) {
      keys.add(cleanDisplay);
    }
  }

  return Array.from(keys).sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
}

function formatKeyChunks(sortedKeys, indent, perLine = 10) {
  const lines = [];
  for (let i = 0; i < sortedKeys.length; i += perLine) {
    const chunk = sortedKeys.slice(i, i + perLine).map((k) => JSON.stringify(k));
    lines.push(`${indent}${chunk.join(", ")}`);
  }
  return lines.join(",\n");
}

function updateKotlinBaseline(sortedKeys) {
  const raw = fs.readFileSync(KT_DB_PATH, "utf8");
  const eol = raw.includes("\r\n") ? "\r\n" : "\n";
  const blockRe =
    /(val STATIC_RELEASED_SHADOW_KEYS:\s*Set<String>\s*=\s*setOf\()([\s\S]*?)(\r?\n\s*\))/;
  const match = blockRe.exec(raw);
  if (!match) {
    throw new Error(`Could not locate STATIC_RELEASED_SHADOW_KEYS block in ${KT_DB_PATH}`);
  }
  const body = "\n" + formatKeyChunks(sortedKeys, "        ", 10);
  const updated = raw.replace(blockRe, `$1${body.replace(/\n/g, eol)}$3`);
  fs.writeFileSync(KT_DB_PATH, updated, "utf8");
}

function writeTsBaseline(sortedKeys) {
  const body = formatKeyChunks(sortedKeys, "  ", 10);
  const content = [
    "// Auto-generated by scripts/sync-pvpoke-shadows.mjs from live PvPoke gamemaster.json — DO NOT EDIT MANUALLY",
    "export const STATIC_RELEASED_SHADOW_KEYS: ReadonlySet<string> = new Set<string>([",
    body,
    "]);",
    "",
  ].join("\n");
  fs.writeFileSync(TS_BASELINE_PATH, content, "utf8");
}

async function main() {
  const gm = await loadGamemaster();
  const sortedKeys = extractShadowKeys(gm);
  if (sortedKeys.length < 400) {
    throw new Error(
      `Extracted only ${sortedKeys.length} shadow keys (< 400 safety floor); aborting overwrite.`
    );
  }

  updateKotlinBaseline(sortedKeys);
  writeTsBaseline(sortedKeys);
  console.log(
    `[shadows:sync] Synced ${sortedKeys.length} Shadow eligibility keys to PokemonDatabase.kt and src/data/shadowBaseline.ts.`
  );

  if (!noWorker) {
    execFileSync(process.execPath, [WORKER_GEN_SCRIPT], { cwd: ROOT, stdio: "inherit" });
  }
}

main().catch((err) => {
  console.error(`[shadows:sync] FAILED: ${err?.stack || err?.message || err}`);
  process.exit(1);
});
